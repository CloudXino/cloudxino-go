#!/usr/bin/env python3
"""Cut the CloudXino API's OpenAPI document down to the public automation contract and make it
OpenAPI 3.0 for oapi-codegen.

    curl -s https://cloudxino.com/api/openapi.json > /tmp/full.json
    python3 scripts/filter_openapi.py /tmp/full.json > openapi/cloudxino.json
    go generate ./...

Keeps the routes under PREFIXES and every schema they reference; turns FastAPI's 3.1
`anyOf: [X, {type: null}]` into `X` + `nullable: true`.
"""

import json
import sys

PREFIXES = (
    "/v1/mc2",
    "/v1/firewalls",
    "/v1/load-balancers",
    "/v1/dns/zones",
    "/v1/projects",
    "/v1/ssh-keys",
    "/v1/reserved-ips",
    "/v1/users/me",
)
# action and console-only routes the SDK does not cover
SKIP = (
    "/terminal", "/cxpanel", "/fix-ssh-key", "/insights", "/alert-policies", "/health/", "/default/get",
    "/accelerator", "/domains", "/options/custom", "/set-default", "/firewalls/options", "/email-records", "/delegate",
    "/reserved-ips/options",
)


# every error answer: docs/API-AUTOMATION.md in the console repository
ERROR = {
    "type": "object",
    "required": ["code"],
    "properties": {
        "code": {"type": "string"},
        "detail": {},
    },
}


def to_30(node):
    """3.1 -> 3.0, and drop the server's free-text descriptions (they speak of its internals)."""
    if isinstance(node, list):
        return [to_30(n) for n in node]
    if not isinstance(node, dict):
        return node
    node = {
        k: to_30(v)
        for k, v in node.items()
        # descriptions speak of the server's internals; extra="allow" is not a promise to clients
        if not (k == "description" and isinstance(v, str)) and not (k == "additionalProperties" and v is True)
    }
    for key in ("anyOf", "oneOf"):
        alts = node.get(key)
        if isinstance(alts, list) and any(a == {"type": "null"} for a in alts):
            rest = [a for a in alts if a != {"type": "null"}]
            del node[key]
            if len(rest) == 1:
                inner = rest[0]
                if "$ref" in inner:
                    node["allOf"] = [inner]
                else:
                    node.update(inner)
            else:
                node[key] = rest
            node["nullable"] = True
    if "examples" in node and isinstance(node["examples"], list):
        examples = node.pop("examples")
        if examples:
            node.setdefault("example", examples[0])
    if node.get("format") == "uuid":  # plain strings in Go: no runtime dependency for the SDK
        del node["format"]
    props = node.get("properties")
    if isinstance(props, dict):  # optional fields are left out of request bodies, not sent as null
        required = set(node.get("required", []))
        for name, prop in props.items():
            if name not in required and isinstance(prop, dict):
                prop["x-omitempty"] = True
    if node.get("const") is not None:
        node["enum"] = [node.pop("const")]
    return node


def refs(node, out):
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
            out.add(ref.rsplit("/", 1)[-1])
        for v in node.values():
            refs(v, out)
    elif isinstance(node, list):
        for v in node:
            refs(v, out)


def main(path):
    spec = json.load(open(path))
    paths = {
        p: ops
        for p, ops in spec["paths"].items()
        if p.startswith(PREFIXES) and not any(s in p for s in SKIP)
    }
    for ops in paths.values():  # FastAPI's 422 schema; errors are described by Error below
        for op in ops.values():
            if isinstance(op, dict):
                op.get("responses", {}).pop("422", None)
    schemas = spec.get("components", {}).get("schemas", {})
    keep, todo = set(), set()
    refs(paths, todo)
    while todo:
        name = todo.pop()
        if name in keep or name not in schemas:
            continue
        keep.add(name)
        refs(schemas[name], todo)
    out = {
        "openapi": "3.0.3",
        "info": {
            "title": "CloudXino API (automation subset)",
            "version": spec.get("info", {}).get("version", "1.0.0"),
            "description": "Generated by scripts/filter_openapi.py from the CloudXino API. Do not edit by hand.",
        },
        "servers": [{"url": "https://cloudxino.com/api"}],
        "components": {
            "schemas": {**{k: to_30(schemas[k]) for k in sorted(keep)}, "Error": ERROR},
            "securitySchemes": {"bearer": {"type": "http", "scheme": "bearer"}},
        },
        "security": [{"bearer": []}],
        "paths": to_30(paths),
    }
    json.dump(out, sys.stdout, indent=2, sort_keys=True)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main(sys.argv[1])
